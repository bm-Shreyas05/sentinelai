"""SQLite persistence: transactions, cases, alerts, audit log and feature-store state.

SQLite in WAL mode handles a single-node deployment comfortably (thousands of writes/sec).
Every function takes an explicit connection so the API, console and MCP server can share one file.
"""
import json, sqlite3, threading, time
from pathlib import Path

SCHEMA = """
CREATE TABLE IF NOT EXISTS transactions (
    txn_id TEXT PRIMARY KEY, user_id TEXT NOT NULL, ts REAL NOT NULL, amount REAL NOT NULL,
    merchant TEXT, payee TEXT, category TEXT, city TEXT, device_id TEXT, channel TEXT,
    score REAL, decision TEXT, model_version TEXT,
    features TEXT, contributions TEXT, reasons TEXT,
    label INTEGER,              -- NULL until an analyst resolves it: 1 fraud, 0 legitimate
    sim_label INTEGER,          -- ground truth when generated by the simulator (never used for scoring)
    created_at REAL NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_txn_user_ts ON transactions(user_id, ts);
CREATE INDEX IF NOT EXISTS ix_txn_created ON transactions(created_at);
CREATE INDEX IF NOT EXISTS ix_txn_decision ON transactions(decision);

CREATE TABLE IF NOT EXISTS cases (
    case_id INTEGER PRIMARY KEY AUTOINCREMENT, txn_id TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'open',   -- open | confirmed_fraud | false_positive
    priority TEXT NOT NULL DEFAULT 'normal', -- normal | high | critical
    summary TEXT, trace TEXT, policy_refs TEXT,
    assignee TEXT, resolution_notes TEXT,
    created_at REAL NOT NULL, updated_at REAL NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_case_status ON cases(status);

CREATE TABLE IF NOT EXISTS alerts (
    alert_id INTEGER PRIMARY KEY AUTOINCREMENT, txn_id TEXT, audience TEXT, channel TEXT,
    status TEXT, body TEXT, created_at REAL NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_log (
    id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL NOT NULL, actor TEXT, action TEXT, detail TEXT
);

CREATE TABLE IF NOT EXISTS user_state (user_id TEXT PRIMARY KEY, state TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS device_users (
    device_id TEXT NOT NULL, user_id TEXT NOT NULL, PRIMARY KEY (device_id, user_id)
);
CREATE TABLE IF NOT EXISTS payee_users (
    payee TEXT NOT NULL, user_id TEXT NOT NULL, PRIMARY KEY (payee, user_id)
);
"""

_lock = threading.Lock()


class _Result:
    """A fully fetched cursor, so no sqlite3 object is touched outside the connection lock."""

    def __init__(self, cur):
        self.rows, self.lastrowid, self.rowcount = cur.fetchall(), cur.lastrowid, cur.rowcount

    def fetchone(self):
        return self.rows[0] if self.rows else None

    def fetchall(self):
        return self.rows

    def __iter__(self):
        return iter(self.rows)


class SharedConnection:
    """One SQLite connection shared by API worker threads, demo traffic and the MCP server.
    sqlite3 objects are not safe to use from several threads at once ("bad parameter or other
    API misuse"), so every statement runs and is fetched under one lock."""

    def __init__(self, conn):
        self._conn, self._lock = conn, threading.RLock()

    def execute(self, sql, params=()):
        with self._lock:
            return _Result(self._conn.execute(sql, params))

    def executescript(self, sql):
        with self._lock:
            self._conn.executescript(sql)

    def executemany(self, sql, seq):
        with self._lock:
            return _Result(self._conn.executemany(sql, seq))

    def __enter__(self):                          # `with conn:` = one transaction, held under the lock
        self._lock.acquire()
        self._conn.__enter__()
        return self

    def __exit__(self, *exc):
        try:
            return self._conn.__exit__(*exc)
        finally:
            self._lock.release()

    def commit(self):
        with self._lock:
            self._conn.commit()

    def close(self):
        with self._lock:
            self._conn.close()


def connect(path) -> SharedConnection:
    path = Path(path)
    if str(path) != ":memory:":
        path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path), check_same_thread=False, timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA synchronous=NORMAL")
    conn.executescript(SCHEMA)
    cols = {r["name"] for r in conn.execute("PRAGMA table_info(transactions)")}
    if "payee" not in cols:                       # databases created before payee support
        conn.execute("ALTER TABLE transactions ADD COLUMN payee TEXT"); conn.commit()
    return SharedConnection(conn)


def audit(conn, actor: str, action: str, detail: dict):
    with _lock:
        conn.execute("INSERT INTO audit_log(ts, actor, action, detail) VALUES (?,?,?,?)",
                     (time.time(), actor, action, json.dumps(detail, default=str)))
        conn.commit()


def row_to_dict(row):
    if row is None:
        return None
    d = dict(row)
    for k in ("features", "contributions", "reasons", "trace", "policy_refs", "detail", "summary"):
        if k in d and isinstance(d[k], str):
            try:
                d[k] = json.loads(d[k])
            except json.JSONDecodeError:
                pass
    return d
